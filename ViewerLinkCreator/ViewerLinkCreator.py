class ViewerLinkCreatorWidget(ScriptedLoadableModuleWidget, VTKObservationMixin):
    """Uses ScriptedLoadableModuleWidget base class, available at:
    https://github.com/Slicer/Slicer/blob/main/Base/Python/slicer/ScriptedLoadableModule.py
    """

    def __init__(self, parent=None) -> None:
        """Called when the user opens the module the first time and the widget is initialized."""
        ScriptedLoadableModuleWidget.__init__(self, parent)
        VTKObservationMixin.__init__(self)  # needed for parameter node observation
        self.logic = None
        self._parameterNode = None
        self._parameterNodeGuiTag = None

    def setup(self) -> None:
        """Called when the user opens the module the first time and the widget is initialized."""
        ScriptedLoadableModuleWidget.setup(self)

        # Load widget from .ui file (created by Qt Designer).
        # Additional widgets can be instantiated manually and added to self.layout.
        uiWidget = slicer.util.loadUI(self.resourcePath("UI/ViewerLinkCreator.ui"))
        self.layout.addWidget(uiWidget)
        self.ui = slicer.util.childWidgetVariables(uiWidget)

        # Set scene in MRML widgets. Make sure that in Qt designer the top-level qMRMLWidget's
        # "mrmlSceneChanged(vtkMRMLScene*)" signal in is connected to each MRML widget's.
        # "setMRMLScene(vtkMRMLScene*)" slot.
        uiWidget.setMRMLScene(slicer.mrmlScene)

        # Create logic class. Logic implements all computations that should be possible to run
        # in batch mode, without a graphical user interface.
        self.logic = ViewerLinkCreatorLogic()

        # Connections

        # These connections ensure that we update parameter node when scene is closed
        self.addObserver(slicer.mrmlScene, slicer.mrmlScene.StartCloseEvent, self.onSceneStartClose)
        self.addObserver(slicer.mrmlScene, slicer.mrmlScene.EndCloseEvent, self.onSceneEndClose)

        self.ui.userLineEdit.textChanged.connect(self.onUpdateLink)
        self.ui.appComboBox.currentIndexChanged.connect(self.onUpdateLink)
        self.ui.pathLineEdit.currentPathChanged.connect(self.onUpdateLink)

        self.ui.updateButton.clicked.connect(self.onUpdateLink)
        self.ui.copyButton.clicked.connect(self.onCopyButtonClicked)

        # Make sure parameter node is initialized (needed for module reload)
        self.initializeParameterNode()

    def onUpdateLink(self):
        args = dict()
        if self.ui.userLineEdit.text:
            args['userName'] = self.ui.userLineEdit.text
        args["applicationId"] = self.ui.appComboBox.currentText

        selectedPath = self.ui.pathLineEdit.currentPath
        if selectedPath:
            if os.path.exists(selectedPath):
                args["args"] = selectedPath
            else:
                slicer.util.warningDisplay(f"Filepath doesn't exist:\n\n'"
                                           f"{selectedPath}'\n\nLink generated without specified filepath.")
                self.ui.pathLineEdit.currentPath = ''

        import urllib
        encodedArgs = urllib.parse.urlencode(args, encoding='utf8')

        self.ui.plainTextEdit.setPlainText(f"{self.ui.baseUrlLineEdit.text}?{encodedArgs}")

    def onCopyButtonClicked(self):
        self.onUpdateLink()
        import sys
        import subprocess
        if sys.platform in ['win32', 'cygwin']:
            subprocess.Popen(['clip'], stdin=subprocess.PIPE).communicate(self.ui.plainTextEdit.plainText.encode('utf8'))
        else:
            print("platform not supported")

    def cleanup(self) -> None:
        """Called when the application closes and the module widget is destroyed."""
        self.removeObservers()

    def enter(self) -> None:
        """Called each time the user opens this module."""
        # Make sure parameter node exists and observed
        self.initializeParameterNode()

    def exit(self) -> None:
        """Called each time the user opens a different module."""
        # Do not react to parameter node changes (GUI will be updated when the user enters into the module)
        if self._parameterNode:
            self._parameterNode.disconnectGui(self._parameterNodeGuiTag)
            self._parameterNodeGuiTag = None
            self.removeObserver(self._parameterNode, vtk.vtkCommand.ModifiedEvent, self._checkCanApply)

    def onSceneStartClose(self, caller, event) -> None:
        """Called just before the scene is closed."""
        # Parameter node will be reset, do not use it anymore
        self.setParameterNode(None)

    def onSceneEndClose(self, caller, event) -> None:
        """Called just after the scene is closed."""
        # If this module is shown while the scene is closed then recreate a new parameter node immediately
        if self.parent.isEntered:
            self.initializeParameterNode()

    def initializeParameterNode(self) -> None:
        """Ensure parameter node exists and observed."""
        # Parameter node stores all user choices in parameter values, node selections, etc.
        # so that when the scene is saved and reloaded, these settings are restored.

        self.setParameterNode(self.logic.getParameterNode())

    def setParameterNode(self, inputParameterNode: Optional[ViewerLinkCreatorParameterNode]) -> None:
        """
        Set and observe parameter node.
        Observation is needed because when the parameter node is changed then the GUI must be updated immediately.
        """

        if self._parameterNode:
            self._parameterNode.disconnectGui(self._parameterNodeGuiTag)
        self._parameterNode = inputParameterNode
        if self._parameterNode:
            # Note: in the .ui file, a Qt dynamic property called "SlicerParameterName" is set on each
            # ui element that needs connection.
            self._parameterNodeGuiTag = self._parameterNode.connectGui(self.ui)



